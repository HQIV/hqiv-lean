def write_generated(payload: dict) -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    tables = {
        "ckm_holonomy.tex": tex_ckm_table(payload),
        "differential_readout.tex": tex_differential_table(payload),
        "phenomenology_edges.tex": tex_phenomenology_table(payload),
        "lean_module_map.tex": tex_lean_module_map(payload),
    }
    for name, body in tables.items():
        (GENERATED / name).write_text(body, encoding="utf-8")
    (PAPER / "data" / "flavor_mixing_witness.json").parent.mkdir(parents=True, exist_ok=True)
    (PAPER / "data" / "flavor_mixing_witness.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )


def bundle_scripts() -> Path:
    scripts_dir = ROOT / "scripts"
    export_script = scripts_dir / "hqiv_flavor_mixing_export.py"
    zip_path = PAPER / "scripts.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(export_script, arcname="hqiv_flavor_mixing_export.py")
        readme = (
            "# Flavor mixing export bundle\n\n"
            "Run from repo root:\n\n"
            "  python3 scripts/hqiv_flavor_mixing_export.py\n\n"
            "Build Lean spine:\n\n"
            "  lake build paper_flavor_mixing\n"
        )
        zf.writestr("README.md", readme)
    return zip_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Export HQIV flavor mixing witness + TeX tables")
    parser.add_argument(
        "--out",
        type=Path,
        default=ROOT / "data" / "flavor_mixing_witness.json",
        help="Output JSON path",
    )
    parser.add_argument("--no-tex", action="store_true", help="Skip TeX table generation")
    parser.add_argument("--no-zip", action="store_true", help="Skip scripts.zip bundle")
    args = parser.parse_args()
    payload = build_witness()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}")
    if not args.no_tex:
        write_generated(payload)
        print(f"Wrote TeX tables under {GENERATED}")
    if not args.no_zip:
        zp = bundle_scripts()
        print(f"Wrote {zp}")


if __name__ == "__main__":
    main()
