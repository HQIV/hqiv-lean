#!/usr/bin/env python3
"""Export flavor-mixing witness JSON and generated TeX tables (Lean-aligned slots)."""

from __future__ import annotations

import argparse
import json
import math
import zipfile
from datetime import datetime, timezone
from pathlib import Path

GAMMA = 2 / 5
CKM_US2 = GAMMA / 8
CKM_CD2 = GAMMA / 16
CKM_CB2 = GAMMA / 32
CP_SKEW = CKM_US2 - CKM_CB2
DELTA_CP = 3 * math.pi / 32
PMNS_DELTA_CP = math.pi / 5
P5_PRIME = 11 / 400
FB_ASYM = 8800 / 160121
BS_FLATNESS = 1 / (1 + CP_SKEW**2)
SIEVERS_DRAG = 3 / 2
SIEVERS_STIFFNESS = 6
SIEVERS_BACKREACTION = 1 / 4

# Reference comparison numerals (outside Lean proof hypotheses).
EXPERIMENTAL = {
    "delta_cp_ckm_deg": 68.5,
    "jarlskog_pdg": 3.08e-5,
    "bs_br_ppb": 2.8,
    "p5_prime_lfhcb": -0.047,
}

ALPHA = 3 / 5
REFERENCE_M = 4


def _shell_shape(m: int) -> float:
    x = m + 1
    return (1 / x) * (1 + ALPHA * math.log(x))


def _curvature_integral(n: int) -> float:
    if n <= 0:
        return 0.0
    return sum(_shell_shape(m) for m in range(n))


def _imprint_phase_at_reference_m() -> float:
    omega = lambda n: _curvature_integral(n) / _curvature_integral(REFERENCE_M)
    delta = omega(REFERENCE_M + 1) - omega(REFERENCE_M)
    phi = 2 * (REFERENCE_M + 1)
    return ALPHA * math.log(phi + 1) * delta


def _jarlskog_parameterization() -> float:
    t12 = math.asin(math.sqrt(CKM_US2))
    t23 = math.asin(math.sqrt(CKM_CB2))
    t13 = math.asin(math.sqrt(CKM_CB2))
    return (
        math.sin(t12) * math.sin(t23) * math.sin(t13) * math.sin(DELTA_CP)
        * math.cos(t12) * math.cos(t23) * math.cos(t13)
    )


def _jarlskog_phenomenology() -> dict:
    j_param = _jarlskog_parameterization()
    ratio = j_param / CP_SKEW
    return {
        "J_ledger": CP_SKEW,
        "J_parameterization": j_param,
        "correction_ratio": ratio,
        "percent_of_ledger": 100 * ratio,
    }


def _longitudinal_phenomenology() -> dict:
    phase = _imprint_phase_at_reference_m()
    corr = 1 + GAMMA * abs(phase)
    p5s = P5_PRIME * corr
    fbs = 2 * p5s / (1 + p5s**2)
    return {
        "imprint_phase_at_referenceM": phase,
        "correction_factor": corr,
        "p5_prime_ppm_shift": (p5s / P5_PRIME - 1) * 1e6,
        "a_fb_ppm_shift": (fbs / FB_ASYM - 1) * 1e6,
    }


def _repo_root() -> Path:
    for parent in Path(__file__).resolve().parents:
        if (parent / "lakefile.toml").exists() and (parent / "data").is_dir():
            return parent
    return Path(__file__).resolve().parents[1]


ROOT = _repo_root()
PAPER = ROOT / "papers" / "flavor_mixing_readout"
GENERATED = PAPER / "generated"


def build_witness() -> dict:
    j_phys = _jarlskog_phenomenology()
    l_phys = _longitudinal_phenomenology()
    return {
        "schema": "hqiv_flavor_mixing_witness_v2",
        "lean_module": "Hqiv.Physics.ProofSpineInventory",
        "python_module": "scripts/hqiv_flavor_mixing_export.py",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "ckm": {
            "V_us2": CKM_US2,
            "V_cd2": CKM_CD2,
            "V_cb2": CKM_CB2,
            "cp_odd_skew": CP_SKEW,
            "delta_cp": DELTA_CP,
            "delta_cp_deg": math.degrees(DELTA_CP),
            "jarlskog_ledger": CP_SKEW,
            "jarlskog_from_angles": j_phys["J_parameterization"],
            "jarlskog_correction_ratio": j_phys["correction_ratio"],
        },
        "pmns": {
            "sin2_theta12": 0.25,
            "sin2_theta23": 1 / 3,
            "delta_cp": PMNS_DELTA_CP,
            "normal_ordering": True,
        },
        "differential": {
            "p5_prime": P5_PRIME,
            "b_to_kstar_mumu_forward_backward": FB_ASYM,
            "bs_to_mumu_angular_flatness": BS_FLATNESS,
            "transverse_weight": 1 - FB_ASYM**2,
        },
        "sievers_bridge": {
            "fiber_drag_kappa7": SIEVERS_DRAG,
            "singlet_stiffness_kappa1": SIEVERS_STIFFNESS,
            "glueball_backreaction": SIEVERS_BACKREACTION,
            "cb_over_us": CKM_CB2 / CKM_US2,
        },
        "certificates": [
            "fanoHolonomyOverlapCertificate_holds",
            "assembleCkmHolonomyReadout",
            "ckmJarlskogFromAngles_eq_sin_delta_sin_cos_envelope",
            "assemblePMNSHolonomyReadout",
            "flavorDifferentialReadoutCertificate_holds",
            "flavorLongitudinalAmplitudeCertificate_holds",
            "gluonSieversHopfBridgeCertificate_holds",
            "proofSpineInventory_holds",
        ],
        "experimental_comparison": EXPERIMENTAL,
        "phenomenology": {
            "jarlskog": j_phys,
            "longitudinal_at_referenceM": l_phys,
        },
    }


